export function getAboutMarkdown(locale?: string | null): string {
  const language = (locale || "en").slice(0, 2).toLowerCase();
  if (language === "zh" || language === "ja" || language === "ko") {
    return ABOUT_MARKDOWN[language];
  }
  return ABOUT_MARKDOWN.en;
}

